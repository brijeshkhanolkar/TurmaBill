/**
 * Ensures at least 10 mock records exist in the database.
 * If the database was previously seeded with fewer records, this complements it.
 */
export async function ensure10MockRecords(force = false): Promise<void> {
  const pattiCount = await db.farmerPattis.count();
  if (pattiCount >= 10 && !force) {
    return;
  }

  await db.transaction('rw', [db.farmers, db.buyers, db.products, db.awaks, db.farmerPattis, db.buyerInvoices, db.inventoryMovements], async () => {
    // 1. Ensure Farmers
    const existingFarmerCount = await db.farmers.count();
    if (existingFarmerCount < INITIAL_FARMERS.length) {
      const existingNames = new Set((await db.farmers.toArray()).map(f => f.name));
      const toAdd = INITIAL_FARMERS.filter(f => !existingNames.has(f.name));
      if (toAdd.length > 0) await db.farmers.bulkAdd(toAdd);
    }

    // 2. Ensure Buyers
    const existingBuyerCount = await db.buyers.count();
    if (existingBuyerCount < INITIAL_BUYERS.length) {
      const existingNames = new Set((await db.buyers.toArray()).map(b => b.name));
      const toAdd = INITIAL_BUYERS.filter(b => !existingNames.has(b.name));
      if (toAdd.length > 0) await db.buyers.bulkAdd(toAdd);
    }

    // 3. Ensure Products
    const existingProductCount = await db.products.count();
    if (existingProductCount < INITIAL_PRODUCTS.length) {
      const existingNames = new Set((await db.products.toArray()).map(p => p.name));
      const toAdd = INITIAL_PRODUCTS.filter(p => !existingNames.has(p.name));
      if (toAdd.length > 0) await db.products.bulkAdd(toAdd);
    }

    // 4. Ensure 10 Awaks
    const existingAwakNos = new Set((await db.awaks.toArray()).map(a => a.awakNo));
    const awaksToAdd = MOCK_10_AWAKS.filter(a => !existingAwakNos.has(a.awakNo));
    if (awaksToAdd.length > 0) await db.awaks.bulkAdd(awaksToAdd);

    // 5. Ensure 10 Pattis
    const existingPattiNos = new Set((await db.farmerPattis.toArray()).map(p => p.pattiNo));
    const pattisToAdd = MOCK_10_PATTIS.filter(p => !existingPattiNos.has(p.pattiNo));
    if (pattisToAdd.length > 0) await db.farmerPattis.bulkAdd(pattisToAdd);

    // 6. Ensure 10 Invoices
    const existingInvoiceNos = new Set((await db.buyerInvoices.toArray()).map(i => i.invoiceNo));
    const invoicesToAdd = MOCK_10_INVOICES.filter(i => !existingInvoiceNos.has(i.invoiceNo));
    if (invoicesToAdd.length > 0) await db.buyerInvoices.bulkAdd(invoicesToAdd);

    // 7. Ensure Inventory movements
    const existingMovements = await db.inventoryMovements.count();
    if (existingMovements < 10) {
      await db.inventoryMovements.bulkAdd(MOCK_10_INVENTORY_MOVEMENTS);
    }
  });
}

